async function prepareWorkspaceFiles(root) {
  const packagePath = path.join(root, 'package.json');
  const packageJson = await readJson(packagePath);
  if (!packageJson) return { prepared: false, reason: 'package.json ausente' };
  packageJson.scripts = {
    ...(packageJson.scripts || {}),
    'workspace:prepare': 'node scripts/prepare-local-workspace.mjs',
    'workspace:dev': 'node scripts/prepare-local-workspace.mjs && vite',
    'workspace:status': 'supabase status',
    'workspace:reset': 'supabase db reset',
  };
  await writeJson(packagePath, packageJson);
  await fs.mkdir(path.join(root, 'scripts'), { recursive: true });
  await fs.writeFile(path.join(root, 'scripts', 'prepare-local-workspace.mjs'), prepareLocalWorkspaceSource(), 'utf8');
  await fs.writeFile(path.join(root, 'DEVELOPMENT_WORKSPACE.md'), workspaceDocumentation(), 'utf8');
  if (!(await pathExists(path.join(root, '.env.local.example')))) {
    await fs.writeFile(path.join(root, '.env.local.example'), 'VITE_RB_DEMO_MODE=false\nVITE_SUPABASE_URL=http://127.0.0.1:54321\nVITE_SUPABASE_PUBLISHABLE_KEY=\n', 'utf8');
  }
  return { prepared: true, mode: 'supabase-local', scripts: ['workspace:prepare', 'workspace:dev', 'workspace:status', 'workspace:reset'] };
}

async function auditRuntimeContracts(root) {
  const files = await listFiles(root, { ignoredDirs: ['node_modules', '.git', 'dist', 'build', 'out', 'release', 'supabase'] });
  const usages = [];
  for (const file of files) {
    if (!/\.(js|jsx|ts|tsx|mjs|cjs)$/i.test(file)) continue;
    const relative = path.relative(root, file).split(path.sep).join('/');
    const source = await fs.readFile(file, 'utf8').catch(() => '');
    usages.push(...extractRuntimeUsages(source, relative));
  }
  const classified = dedupeUsages(usages).map(classifyRuntimeUsage);
  return {
    usages: classified,
    converted: classified.filter((usage) => usage.support === 'converted'),
    bridged: classified.filter((usage) => usage.support === 'bridged'),
    emulated: classified.filter((usage) => usage.support === 'emulated'),
    unsupported: classified.filter((usage) => usage.support === 'unsupported'),
  };
}

async function auditEntityMethods(root) {
  const audit = await auditRuntimeContracts(root);
  const usages = audit.usages.filter((usage) => usage.kind === 'entity' || usage.kind === 'service-role-entity');
  return { usages, unsupported: usages.filter((usage) => usage.support === 'unsupported') };
}

function runtimeMarkdown(audit, workspace) {
  const rows = audit.usages.length
    ? audit.usages.map((item) => `| ${item.namespace}${item.entity ? '.' + item.entity : ''}.${item.method} | ${item.support} | ${item.file} |`).join('\n')
    : '| Nenhum contrato detectado | — | — |';
  return `# Compatibilidade de runtime\n\n- Convertidos: ${audit.converted.length}\n- Encaminhados por adapter: ${audit.bridged.length}\n- Emulados: ${audit.emulated.length}\n- Não suportados: ${audit.unsupported.length}\n- Workspace local: ${workspace.prepared ? 'preparado' : 'não preparado'}\n\n| Contrato | Tratamento | Arquivo |\n|---|---|---|\n${rows}\n\nContratos emulados funcionam no sandbox, mas precisam de decisão explícita antes de produção. Contratos não suportados bloqueiam a aprovação do preview.\n`;
}

async function applyRuntimeCompatibility(root) {
  const adapterPath = path.join(root, 'src', 'api', 'base44Client.js');
  if (!(await pathExists(adapterPath))) {
    return { applied: false, adapter: null, serviceWorkerPatched: false, workspace: { prepared: false }, usages: [], converted: [], bridged: [], emulated: [], unsupported: [] };
  }

  const adapterSource = await fs.readFile(adapterPath, 'utf8');
  const adapter = patchGeneratedAdapterSource(adapterSource);
  if (adapter.patched) await fs.writeFile(adapterPath, adapter.source, 'utf8');

  let serviceWorkerPatched = false;
  for (const candidate of ['src/main.jsx', 'src/main.tsx', 'src/main.js', 'src/main.ts']) {
    const file = path.join(root, candidate);
    if (!(await pathExists(file))) continue;
    const source = await fs.readFile(file, 'utf8');
    const patched = patchDemoServiceWorkerSource(source);
    if (patched !== source) {
      await fs.writeFile(file, patched, 'utf8');
      serviceWorkerPatched = true;
    }
    break;
  }

  const workspace = await prepareWorkspaceFiles(root);
  const audit = await auditRuntimeContracts(root);
  const inventory = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    workspace,
    usages: audit.usages,
    summary: {
      converted: audit.converted.length,
      bridged: audit.bridged.length,
      emulated: audit.emulated.length,
      unsupported: audit.unsupported.length,
    },
  };
  await writeJson(path.join(root, 'RB-RUNTIME-CONTRACTS.json'), inventory);
  await fs.writeFile(path.join(root, 'RUNTIME_COMPATIBILITY.md'), runtimeMarkdown(audit, workspace), 'utf8');

  if (audit.unsupported.length) {
    throw new BridgeError(
      'UNSUPPORTED_BASE44_RUNTIME_METHOD',
      `A aplicação usa contratos Base44 ainda não convertidos: ${audit.unsupported.slice(0, 6).map((item) => `${item.namespace}.${item.method} em ${item.file}`).join(', ')}${audit.unsupported.length > 6 ? '…' : ''}`,
      {
        unsupported: audit.unsupported,
        supportedEntityMethods: [...SUPPORTED_ENTITY_METHODS],
        supportedAuthMethods: [...SUPPORTED_AUTH_METHODS],
        supportedAppLogMethods: [...SUPPORTED_APP_LOG_METHODS],
      },
    );
  }

  return {
    applied: adapter.patched || serviceWorkerPatched || workspace.prepared,
    adapter: path.relative(root, adapterPath).split(path.sep).join('/'),
    adapterPatched: adapter.patched,
    upgradedFromV1: adapter.upgradedFromV1,
    serviceWorkerPatched,
    workspace,
    usages: audit.usages,
    converted: audit.converted,
    bridged: audit.bridged,
    emulated: audit.emulated,
    unsupported: [],
  };
}

