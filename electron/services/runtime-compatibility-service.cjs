'use strict';

const fs = require('node:fs/promises');
const path = require('node:path');
const { listFiles, pathExists } = require('../core/fs-utils.cjs');
const { BridgeError } = require('../core/errors.cjs');

const SUPPORTED_ENTITY_METHODS = new Set([
  'list', 'filter', 'get', 'create', 'bulkCreate', 'update', 'delete', 'subscribe',
]);

const COMPATIBILITY_MARKER = 'RB_RUNTIME_COMPAT_V1';

function extractEntityMethodUsages(source, filePath = '') {
  const usages = [];
  const pattern = /base44\.entities(?:\.([A-Za-z_$][\w$]*)|\[['"]([^'"]+)['"]\])(?:\?\.)?\.([A-Za-z_$][\w$]*)/g;
  for (const match of String(source || '').matchAll(pattern)) {
    usages.push({ file: filePath, entity: match[1] || match[2], method: match[3], expression: match[0] });
  }
  return usages;
}

function realtimeCompatibilitySource() {
  return `
// ${COMPATIBILITY_MARKER}: generated by RB Project Bridge.
function normalizeRealtimeEvent(payload = {}) {
  const eventType = String(payload.eventType || payload.type || '').toLowerCase();
  const type = eventType === 'insert' ? 'create' : eventType === 'delete' ? 'delete' : eventType === 'update' ? 'update' : eventType;
  const row = payload.new && Object.keys(payload.new).length ? payload.new : payload.old || null;
  return { type, id: row?.id || payload.old?.id || null, data: decorate(row), old: decorate(payload.old || null), raw: payload };
}
function subscribeToEntity(entity, callback) {
  if (typeof callback !== 'function') return () => {};
  if (demoMode || !supabase) return () => {};
  const table = tableFor(entity);
  const suffix = globalThis.crypto?.randomUUID?.() || Math.random().toString(36).slice(2);
  const channel = supabase
    .channel('rb-bridge-' + table + '-' + suffix)
    .on('postgres_changes', { event: '*', schema: 'public', table }, (payload) => callback(normalizeRealtimeEvent(payload)))
    .subscribe();
  return () => { try { void supabase.removeChannel(channel); } catch {} };
}
const compatibleEntities = new Proxy(entities, {
  get: (_target, entity) => {
    const adapter = entities[entity];
    return { ...adapter, subscribe: (callback) => subscribeToEntity(String(entity), callback) };
  },
});
`;
}

function patchGeneratedAdapterSource(source) {
  const text = String(source || '');
  if (text.includes(COMPATIBILITY_MARKER)) return { source: text, patched: false };
  const exportMarker = 'export { supabase, demoMode };';
  const base44Marker = 'export const base44 = { entities, auth,';
  if (!text.includes(exportMarker) || !text.includes(base44Marker)) {
    throw new BridgeError(
      'STANDALONE_ADAPTER_PATCH_FAILED',
      'O adapter standalone gerado não possui a estrutura esperada para compatibilidade em tempo de execução.',
    );
  }
  let patched = text.replace(exportMarker, `${realtimeCompatibilitySource()}\n${exportMarker}`);
  patched = patched.replace(base44Marker, 'export const base44 = { entities: compatibleEntities, auth,');
  patched = patched.replace('asServiceRole: { entities, integrations:', 'asServiceRole: { entities: compatibleEntities, integrations:');
  return { source: patched, patched: true };
}

function patchDemoServiceWorkerSource(source) {
  let patched = String(source || '');
  patched = patched.replace(
    /if\s*\(\s*'serviceWorker'\s+in\s+navigator\s*&&\s*!import\.meta\.env\.DEV\s*\)/,
    "if ('serviceWorker' in navigator && !import.meta.env.DEV && import.meta.env.VITE_RB_DEMO_MODE !== 'true')",
  );
  patched = patched.replace(
    /else\s+if\s*\(\s*'serviceWorker'\s+in\s+navigator\s*&&\s*import\.meta\.env\.DEV\s*\)/,
    "else if ('serviceWorker' in navigator && (import.meta.env.DEV || import.meta.env.VITE_RB_DEMO_MODE === 'true'))",
  );
  return patched;
}

async function auditEntityMethods(root) {
  const files = await listFiles(root, { ignoredDirs: ['node_modules', '.git', 'dist', 'build', 'out', 'release', 'supabase'] });
  const usages = [];
  for (const file of files) {
    if (!/\.(js|jsx|ts|tsx|mjs|cjs)$/i.test(file)) continue;
    const relative = path.relative(root, file).split(path.sep).join('/');
    const source = await fs.readFile(file, 'utf8').catch(() => '');
    usages.push(...extractEntityMethodUsages(source, relative));
  }
  const unsupported = usages.filter((usage) => !SUPPORTED_ENTITY_METHODS.has(usage.method));
  return { usages, unsupported };
}

async function applyRuntimeCompatibility(root) {
  const adapterPath = path.join(root, 'src', 'api', 'base44Client.js');
  if (!(await pathExists(adapterPath))) {
    return { applied: false, adapter: null, serviceWorkerPatched: false, usages: [], unsupported: [] };
  }

  const adapterSource = await fs.readFile(adapterPath, 'utf8');
  const adapter = patchGeneratedAdapterSource(adapterSource);
  if (adapter.patched) await fs.writeFile(adapterPath, adapter.source, 'utf8');

  let serviceWorkerPatched = false;
  for (const candidate of ['src/main.jsx', 'src/main.tsx', 'src/main.js', 'src/main.ts']) {
    const file = path.join(root, candidate);
    if (!(await pathExists(file))) continue;
    const source = await fs.readFile(file, 'utf8');
    const patched = patchDemoServiceWorkerSource(source);
    if (patched !== source) {
      await fs.writeFile(file, patched, 'utf8');
      serviceWorkerPatched = true;
    }
    break;
  }

  const audit = await auditEntityMethods(root);
  if (audit.unsupported.length) {
    throw new BridgeError(
      'UNSUPPORTED_BASE44_RUNTIME_METHOD',
      `A aplicação usa métodos Base44 ainda não convertidos: ${audit.unsupported.slice(0, 6).map((item) => `${item.entity}.${item.method} em ${item.file}`).join(', ')}${audit.unsupported.length > 6 ? '…' : ''}`,
      { unsupported: audit.unsupported, supportedMethods: [...SUPPORTED_ENTITY_METHODS] },
    );
  }

  return {
    applied: adapter.patched || serviceWorkerPatched,
    adapter: path.relative(root, adapterPath).split(path.sep).join('/'),
    adapterPatched: adapter.patched,
    serviceWorkerPatched,
    usages: audit.usages,
    unsupported: [],
  };
}

module.exports = {
  SUPPORTED_ENTITY_METHODS,
  COMPATIBILITY_MARKER,
  extractEntityMethodUsages,
  patchGeneratedAdapterSource,
  patchDemoServiceWorkerSource,
  auditEntityMethods,
  applyRuntimeCompatibility,
};
