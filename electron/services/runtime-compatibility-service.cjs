function patchGeneratedAdapterSource(source) {
  const text = String(source || '');
  const exportMarker = 'export { supabase, demoMode };';
  if (!text.includes(exportMarker) || !text.includes('export const base44 = {')) {
    throw new BridgeError(
      'STANDALONE_ADAPTER_PATCH_FAILED',
      'O adapter standalone gerado não possui a estrutura esperada para compatibilidade em tempo de execução.',
    );
  }

  let patched = text;
  let changed = false;
  const hasCompatibleEntities = patched.includes('const compatibleEntities = new Proxy');
  if (!hasCompatibleEntities) {
    patched = patched.replace(exportMarker, `${realtimeCompatibilitySource()}\n${exportMarker}`);
    patched = patched.replace('export const base44 = { entities, auth,', 'export const base44 = { entities: compatibleEntities, auth,');
    patched = patched.replace('asServiceRole: { entities, integrations:', 'asServiceRole: { entities: compatibleEntities, integrations:');
    changed = true;
  }

  if (!patched.includes('const appLogs = {')) {
    patched = patched.replace(exportMarker, `${appLogsCompatibilitySource()}\n${exportMarker}`);
    changed = true;
  }

  if (patched.includes('export const base44 = { entities: compatibleEntities, auth,') && !patched.includes('export const base44 = { entities: compatibleEntities, auth, appLogs,')) {
    patched = patched.replace('export const base44 = { entities: compatibleEntities, auth,', 'export const base44 = { entities: compatibleEntities, auth, appLogs,');
    changed = true;
  }
  if (patched.includes('export const base44 = { entities, auth,') && !patched.includes('export const base44 = { entities, auth, appLogs,')) {
    patched = patched.replace('export const base44 = { entities, auth,', 'export const base44 = { entities, auth, appLogs,');
    changed = true;
  }

  return { source: patched, patched: changed, upgradedFromV1: text.includes(LEGACY_COMPATIBILITY_MARKER) && !text.includes(COMPATIBILITY_MARKER) };
}

function patchDemoServiceWorkerSource(source) {
  let patched = String(source || '');
  patched = patched.replace(
    /if\s*\(\s*'serviceWorker'\s+in\s+navigator\s*&&\s*!import\.meta\.env\.DEV\s*\)/,
    "if ('serviceWorker' in navigator && !import.meta.env.DEV && import.meta.env.VITE_RB_DEMO_MODE !== 'true')",
  );
  patched = patched.replace(
    /else\s+if\s*\(\s*'serviceWorker'\s+in\s+navigator\s*&&\s*import\.meta\.env\.DEV\s*\)/,
    "else if ('serviceWorker' in navigator && (import.meta.env.DEV || import.meta.env.VITE_RB_DEMO_MODE === 'true'))",
  );
  return patched;
}

